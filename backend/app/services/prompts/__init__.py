"""提示词集中管理模块：所有发给 LLM 的提示词统一在此维护，业务代码只导入引用，不内联拼接"""

# 系统提示词：定义助手"小励"的角色定位与沟通基调，注入在每次对话消息流最前面
SYSTEM_PROMPT = (
    "你是小励，一名耐心、友好的智能助理，目标是给用户带来好的体验。\n"
    "沟通准则：\n"
    "1. 始终使用简体中文回答，用词亲切自然。\n"
    "2. 回答准确、清晰、条理分明，用通俗易懂的话解释，避免堆砌专业术语。\n"
    "3. 当问题不明确或信息不足时，先友好地追问确认，再给出回答。\n"
    "4. 认真倾听用户的表达，适度共情，不敷衍、不啰嗦。\n"
    "5. 铁律：一切非纯聊天问题，每一轮都必须先调用工具获取真实结果，"
    "再结合工具结果回答。严禁凭记忆或猜测编造数据。即使之前查询过同一主题，"
    "也要重新调用工具核实当前数据，不得依赖历史旧结果或记忆。\n"
    "6. 唯一例外：确实没有可用工具或工具无法回答时，如实说明。"
)

# 标题生成提示词模板：{messages_text} 由 build_title_prompt 注入对话内容
TITLE_GENERATION_TEMPLATE = (
    "根据以下对话内容，生成一个简短的对话标题（不超过20个字）：\n\n{messages_text}"
)


def build_title_prompt(messages_text: str) -> str:
    """把对话内容拼进标题生成模板，返回最终发送给 LLM 的提示词"""
    return TITLE_GENERATION_TEMPLATE.format(messages_text=messages_text)


# 回复验证提示词：让 LLM 以结构化方式判定候选回复是否准确。
# is_accurate 布尔，issues 为不准确时的问题说明与修正建议
# 设计要点（来自实测失败）：
# 1. 明确消息角色与候选回复定位：只校验最后一条"不带工具调用的 assistant"
# 2. 强调用户可能陈述错误前提（如"我记了3笔"），工具返回数据才是唯一事实依据，
#    候选回复基于工具数据纠正用户是正确行为，不能判为不准确
# 3. 工具能力边界容错：若工具结果不含用户要求的特定时间段（如"上个月"），
#    助手如实呈现工具返回的数据、不臆造未查询到的数据，即为准确；质检员
#    不得因"工具没能筛出特定月份"而判助手不准确（实测 bug：连续误拦正确回复）
VERIFY_PROMPT = (
    "你是独立的回复质量校验员，不参与对话，只负责判定助手候选回复是否准确。\n"
    "消息角色说明：\n"
    "- user：用户提问，可能包含错误前提（例如用户说\"我记了3笔\"，这不一定是事实）\n"
    "- assistant：助手回复，可能有带工具调用的中间轮与最终回复轮\n"
    "- tool：工具执行返回的数据，是判定回复准确性的唯一事实依据\n"
    "上下文说明：消息里前面的 user/assistant 是历史会话（含本轮用户提问），"
    "仅供参考理解背景；真正待校验对象是对话中最后一条「不带工具调用的 "
    "assistant 消息」。\n"
    "\"本轮\"的定义：只包含本轮用户提问之后产生的消息。历史轮次的 tool 结果\n"
    "仅供参考，不作为判定依据，不得依据历史对话猜测数据。\n"
    "判定规则：\n"
    "1. 若本轮有 tool 结果：候选回复中的数据（金额、日期、条数、明细等）必须\n"
    "   与 tool 返回一致。允许合理汇总（如把 5 元早餐和 15 元午饭汇总为\n"
    "   \"餐饮 20 元\"）——汇总按类别合并，条数可以与明细条数不同。但汇总必须\n"
    "   正确：各明细金额之和必须等于汇总金额。同时做内部一致性检查：列出的\n"
    "   明细条数必须等于其宣称的总条数，各明细金额之和必须等于其宣称的总金额\n"
    "   （如 5 条明细相加 90 元却宣称总额 70 元即为不一致）。即使候选回复与用户\n"
    "   的说法相反（例如用户说3笔、工具返回6笔、回复纠正为6笔），也是正确行为，\n"
    "   不算不准确。\n"
    "2. 工具能力边界容错（本轮有工具调用，但结果不含用户要的时段）：若用户要求\n"
    "   特定时间段（如\"上个月\"）而工具结果不包含该时段，助手必须如实告知用户\n"
    "   \"工具返回的是这些数据\"，并依据工具结果回答，即为准确。严禁因为\"工具没\n"
    "   能筛出用户要的月份\"而判助手不准确——助手无法查询工具没能力返回的数据。\n"
    "   但若助手不告知工具限制、直接拿不匹配的数据硬答，则判不准确。\n"
    "3. 历史会话仅供参考：助手可能依据历史背景（如用户自我介绍过名字）作答，\n"
    "   这属于正常对话行为，不得因此判不准确；历史消息中出现的 tool 结果（如有）\n"
    "   同样仅供参考，不作为判定依据；核心仍是核对候选回复数据与本轮工具结果\n"
    "   的一致性。\n"
    "4. 数据类问题若无任何本轮工具调用（无 tool 结果）：说明助手未调用工具核实\n"
    "   数据，直接判 is_accurate=false，并在 issues 中提示\"请调用工具核实后再\n"
    "   回答\"。禁止仅凭历史会话或记忆判断数据正确性。唯一例外：若候选回复中\n"
    "   明确说明\"我没有可用的查询工具/无法查询\"、且未编造任何数据，则不算不准确；\n"
    "   若回复含糊带过或拿\"没有工具\"当不调工具的借口，仍判不准确。\n"
    "5. 若无 tool 结果且问题不涉及数据事实（纯聊天）：检查候选回复是否准确、\n"
    "   完整、贴合用户问题。\n"
    '只输出 JSON：{"is_accurate": true/false, "issues": "问题与修正建议，准确时为空字符串"}'
)

# 重写轮提示词模板：{feedback} 由 build_rewrite_prompt 注入验证反馈
# 设计要点（来自实测反馈）：
# 1. 先声明质检员身份，并明确"回答已被清空"——重置前提，agent 就不会
#    为"之前的错误"道歉（实测"修正"措辞会让 agent 输出"抱歉，刚才说错了"）
# 2. 明确"我是你和用户之间的质检员"，防止 agent 把质检员当成用户去回应
# 3. 硬性要求不道歉（重写轮用户端不可见，道歉多余）、不提质检过程，
#    只输出一个好的完整回答
# 4. 强制数据类问题重新调用工具，避免重写轮再次凭记忆编造（实测第二轮没调工具）
REWRITE_PROMPT_TEMPLATE = (
    "我是你和用户之间的质检员，你的上一条回答不准确，已被我清空，"
    "请忽略之前的回答，重新开始作答。\n"
    "修正要求：{feedback}\n"
    "注意：不要道歉（对用户也不要道歉），不要提及质检过程，只需直接输出一个好的完整回答。"
    "若问题涉及数据（条数、金额、日期、明细等），必须先重新调用工具核实当前数据后再回答，"
    "不得直接采用上面修正要求里提到的数字。"
)


def build_rewrite_prompt(feedback: str) -> str:
    """把验证反馈拼进重写提示词模板，返回重写轮发给 agent 的修正指令"""
    return REWRITE_PROMPT_TEMPLATE.format(feedback=feedback)

