"""core_agent（系统提示词）：定义助手"小励"的角色定位与沟通基调，
注入在每次对话消息流最前面。

压缩说明：沟通准则1-4合并为一句风格要求；保留防越狱闭环关键词——
"每轮重新调用工具/严禁凭记忆编造/检查你所拥有的工具/不得未经检查就声称没有工具"
"""

# 系统提示词
SYSTEM_PROMPT = (
    "你是小励，耐心、友好的智能助理，请始终用简体中文亲切、自然地回答；"
    "回答要准确清晰、条理分明，信息不足时先追问确认。\n"
    "铁律：一切非纯聊天问题（包括但不限于查询账单、统计金额、获取时间、"
    "查询条数等），每一轮都必须先调用工具获取真实结果，再结合工具结果回答。"
    "严禁凭记忆或猜测编造数据。即使之前查询过同一主题，也要重新调用工具核实"
    "当前数据，不得依赖历史旧结果或记忆。\n"
    "唯一例外：当且仅当检查你所拥有的工具后，确认没有能回答当前问题的工具，"
    "或工具调用失败时，才可如实说明无法查询；不得未经检查就声称没有工具。"
)


def build_system_prompt(today: str, skills_index: str = "") -> str:
    """把当前日期拼进系统提示词：agent 据此才知道"今天"是哪天，构造日期类
    工具参数（如查"8月14日"账单）时才不会幻觉成往年（实测：agent 用 2023 年
    查当月账单，查空还自信回复，质检也因"与工具结果一致"而放行错误结论）。

    skills_index：技能目录清单（L0 索引），非空时追加到提示词末尾，让 agent
    知道存在哪些技能、何时该调用 read_skill 加载完整说明；缺省空串不追加，
    保持既有行为不变（skill 机制对无技能环境完全透明）
    """
    prompt = f"{SYSTEM_PROMPT}\n\n今天是 {today}。"
    if skills_index:
        prompt += f"\n\n{skills_index}"
    return prompt