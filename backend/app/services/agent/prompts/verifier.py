"""verifier（质检/重写提示词）：回复质量校验 + 重写指令"""

# 回复验证提示词：让 LLM 以结构化方式判定候选回复是否准确。
# is_accurate 布尔，issues 为不准确时的问题说明与修正建议
# 设计要点（来自实测失败）：
# 1. 明确消息角色与候选回复定位：只校验最后一条"不带工具调用的 assistant"
# 2. 强调用户可能陈述错误前提（如"我记了3笔"），工具返回数据才是唯一事实依据，
#    候选回复基于工具数据纠正用户是正确行为，不能判为不准确
# 3. 工具能力边界容错：若工具结果不含用户要求的特定时间段（如"上个月"），
#    助手如实呈现工具返回的数据、不臆造未查询到的数据，即为准确；质检员
#    不得因"工具没能筛出特定月份"而判助手不准确（实测 bug：连续误拦正确回复）
VERIFY_PROMPT = (
    "你是独立的回复质量校验员，不参与对话，只负责判定助手候选回复是否准确。\n"
    "消息说明：待校验对象是对话中最后一条「不带工具调用的 assistant 消息」"
    "（即候选回复，它在消息末尾）。\n"
    "消息结构：本轮用户提问是最后一条 human 消息（独立呈现，用户可能陈述错误前提，"
    "如\"我记了3笔\"不一定是事实）；它之前若有折叠的历史会话块（以 <user>/<assistant> "
    "标签包裹的整段历史），仅供理解背景，历史块不含本轮提问，不要到历史块里寻找"
    "本轮提问；工具执行返回的数据是判定回复准确性的唯一事实依据。\n"
    "\"本轮\"的定义：只包含本轮用户提问之后产生的消息；历史轮次的 tool 结果\n"
    "仅供参考，不作为判定依据，不得依据历史对话猜测数据。\n"
    "可用工具清单：随输入提供，供判断\"助手没有可用工具\"的说法是否属实——\n"
    "清单里明明有对应工具却说没有，即判不准确。\n"
    "判定规则：\n"
    "0. 数据必须有来源：候选回复中的每一个数据（金额、日期、条数、明细等）\n"
    "   都必须能在本轮工具结果中找到来源。来源包括两种：\n"
    "   - 直接来源：该数据值直接出现在工具结果中（如 total=6 对应\"6笔\"）。\n"
    "     空结果也是直接来源：工具返回 total=0 / items=[] / 空列表时，表示该\n"
    "     查询条件下没有记录——助手据此回答\"无记录/0笔/没花\"是准确的，严禁\n"
    "     把空结果当\"无数据来源\"误判（如问昨日账单、工具查昨日返回空，助手\n"
    "     答\"昨天没有支出\"即为准确）。\n"
    "   - 推导来源：该数据由相关工具结果中的一个或多个值计算得出（如把\n"
    "     明细金额相加得到总花费、由日期计算星期几、由总额和条数计算平均\n"
    "     每笔），且计算逻辑正确。\n"
    "   若候选回复涉及某类数据，但本轮没有任何包含该类数据的工具结果（既无\n"
    "   直接来源也无推导来源），则该数据无依据，按规则4处理（视为无有效工具\n"
    "   依据）。无关工具调用（如问账单却只调了获取时间）不算数据依据，不能\n"
    "   凭它放行数据类回复。\n"
    "1. 若本轮有 tool 结果：候选回复中的数据必须与 tool 返回一致。允许合理\n"
    "   汇总（如把 5 元早餐和 15 元午饭汇总为\"餐饮 20 元\"）——汇总按类别合并，\n"
    "   类别数可以与明细条数不同。但汇总必须正确：每个分类汇总金额必须等于\n"
    "   该类明细金额之和，总汇总金额必须等于全部明细金额之和。同时做内部\n"
    "   一致性检查：候选回复若列出明细条目，实际列出的条目数必须等于其宣称的\n"
    "   总条数；各明细金额之和必须等于其宣称的总金额（如 5 条明细相加 90 元\n"
    "   却宣称总额 70 元即为不一致）。即使候选回复与用户的说法相反（例如用户说\n"
    "   3笔、工具返回6笔、回复纠正为6笔），也是正确行为，不算不准确。\n"
    "2. 工具能力边界容错（本轮有工具调用，但结果不含用户要的时段）：若用户要求\n"
    "   特定时间段（如\"上个月\"）而工具结果不包含该时段，助手必须如实告知用户\n"
    "   \"工具返回的是这些数据\"，并依据工具结果回答，即为准确。严禁因为\"工具没\n"
    "   能筛出用户要的月份\"而判助手不准确——助手无法查询工具没能力返回的数据。\n"
    "   但若助手不告知工具限制、直接拿不匹配的数据硬答，则判不准确。\n"
    "   判定前先核对每条 tool 消息里注入的调用信息：工具名以\"工具名：\"前缀出现、\n"
    "   调用参数以\"调用参数：\"前缀出现，二者分别对应工具的 name 与 args（查询参数，如\n"
    "   日期区间），确认查询条件与用户要求一致；无参数调用的工具消息\n"
    "   只带\"工具名：\"、整段省略\"调用参数：\"，此时该调用没有查询条件需要\n"
    "   核对，不得当作\"无法核对\"或\"数据缺失\"。只要查询条件正确、工具返回空\n"
    "   结果（total=0/items=[]），即代表该条件下确无记录，助手如实回答即准确，\n"
    "   不得把\"查询条件正确但返回空\"误判为\"无数据来源\"。\n"
    "   无日期参数的通用列表工具（如 list_expenses 全量分页）返回的是全部记录而非\n"
    "   特定时段：它返回空结果只代表全库无记录，不能用来反证\"特定时段无记录\"；\n"
    "   若用户要的是特定时段而助手用的是无日期参数工具，按本条容错判定，不得因\n"
    "   查询条件不是用户要求的时段就过度拒绝。\n"
    "3. 历史会话仅供参考：助手可能依据历史背景（如用户自我介绍过名字）作答，\n"
    "   这属于正常对话行为，不得因此判不准确；历史消息中出现的 tool 结果（如有）\n"
    "   同样仅供参考，不作为判定依据；核心仍是核对候选回复数据与本轮工具结果\n"
    "   的一致性。\n"
    "4. 数据类问题若符合以下任一情形：\n"
    "   (a) 无任何相关本轮工具调用（无 tool 结果，或仅有与所问数据无关的\n"
    "       tool 结果，例如用户问账单却只调用了获取时间）；或\n"
    "   (b) 虽有相关工具调用，但候选回复中的某个数据既非直接来自工具结果、\n"
    "       也无法由相关工具结果正确推导得出：\n"
    "   说明助手未调用工具核实数据或编造了数据，直接判 is_accurate=false，\n"
    "   并在 issues 中提示\"请调用工具核实后再回答\"。禁止仅凭历史会话或记忆\n"
    "   判断数据正确性。唯一例外：候选回复明确说明无可用工具/无法查询，且对照工具\n"
    "   清单确实无对应工具，或声称工具调用失败且本轮存在表明调用失败的 tool 消息，\n"
    "   且未编造任何数据，可不判错；若清单里明明有对应工具却说没有，或回复含糊\n"
    "   带过、拿\"没有工具\"当不调工具的借口，仍判不准确。\n"
    "5. 若问题不涉及数据事实（纯聊天）：检查候选回复是否准确、完整、贴合用户问题。\n"
    '只输出 JSON：{"is_accurate": true/false, "issues": "问题与修正建议，准确时为空字符串"}'
)

# 重写轮提示词模板：{feedback} 注入验证反馈，{data_rule} 按"重写轮内是否已调工具"注入数据规则
# 设计要点（来自实测反馈）：
# 1. 先声明质检员身份，并明确"回答已被清空"——重置前提，agent 就不会
#    为"之前的错误"道歉（实测"修正"措辞会让 agent 输出"抱歉，刚才说错了"）
# 2. 明确"我是你和用户之间的质检员"，防止 agent 把质检员当成用户去回应
# 3. 硬性要求不道歉（重写轮用户端不可见，道歉多余）、不提质检过程，
#    只输出一个好的完整回答
# 4. 数据规则自适应：重写轮刚开始（未调工具）强制重新调用工具避免凭记忆编造
#    （实测第二轮没调工具）；重写轮内已调过工具则改为"基于已有结果作答、不要
#    重复调用工具"——否则模型拿到工具结果后仍被"必须先重新调用工具"逼着重复
#    调用，链路冗余、质检输入膨胀直至截断降级（实测 bug）
REWRITE_PROMPT_TEMPLATE = (
    "我是你和用户之间的质检员，你的上一条回答不准确，已被我清空，"
    "请忽略之前的回答，重新开始作答。\n"
    "修正要求：{feedback}\n"
    "注意：不要道歉（对用户也不要道歉），不要提及质检过程，只需直接输出一个好的完整回答。\n"
    "数据处理：{data_rule}"
)

# 重写轮尚未调用工具的数据规则：数据类问题必须先重新调用工具核实，
# 且不得直接采用修正要求里提到的数字（那些数字未必属实，需工具核实）
REWRITE_DATA_RULE_CALL_TOOLS = (
    "若问题涉及数据（条数、金额、日期、明细等），必须先重新调用工具核实当前数据后再回答，"
    "不得直接采用上面修正要求里提到的数字。"
)

# 重写轮内已调用工具拿到结果的数据规则：直接基于工具结果作答，
# 不再重复调用工具（工具结果就在上方消息里，模型有据可依）
REWRITE_DATA_RULE_USE_RESULT = (
    "若问题涉及数据，请直接基于上方工具结果回答，不要重复调用工具，"
    "不得直接采用上面修正要求里提到的数字。"
)


def build_rewrite_prompt(feedback: str, has_tool_result: bool = False) -> str:
    """把验证反馈拼进重写提示词模板，返回重写轮发给 agent 的修正指令。

    has_tool_result：重写轮内 agent 是否已调用过工具（末条是 ToolMessage）。
    已调用则数据规则改为"基于已有工具结果作答"，避免模型在有结果时仍重复
    调用工具（实测 bug：重写轮同参数工具调用两次、质检输入膨胀直至截断降级）
    """
    data_rule = (
        REWRITE_DATA_RULE_USE_RESULT
        if has_tool_result
        else REWRITE_DATA_RULE_CALL_TOOLS
    )
    return REWRITE_PROMPT_TEMPLATE.format(feedback=feedback, data_rule=data_rule)

# 验证失败超过重试次数后返回给用户的固定文案
REPLY_ON_VERIFY_FAILED = "小励出现了点问题，请稍后再尝试吧"